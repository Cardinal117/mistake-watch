import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { randomUUID } from "node:crypto";

// Explicitly local-only: never accepts a connection URL or arbitrary database.
if (!process.argv.includes("--local-fixture")) {
  throw new Error(
    "Pass --local-fixture to verify the disposable local database.",
  );
}
const container = "supabase_db_mistake-watch-task028";
const database = "task030_catalogue_replay";
const account = randomUUID();
const recording = randomUUID();
const source = `qa2${randomUUID().replaceAll("-", "")}`;
function sql(statement) {
  return new Promise((resolve, reject) => {
    const child = spawn(
      "docker",
      [
        "exec",
        "-i",
        container,
        "psql",
        "-U",
        "postgres",
        "-d",
        database,
        "-v",
        "ON_ERROR_STOP=1",
        "-v",
        "VERBOSITY=sqlstate",
        "-q",
        "-At",
      ],
      { windowsHide: true },
    );
    let stdout = "",
      stderr = "";
    child.stdout.on("data", (chunk) => {
      stdout += chunk;
    });
    child.stderr.on("data", (chunk) => {
      stderr += chunk;
    });
    child.on("error", reject);
    child.on("close", (code) =>
      resolve({ code, stdout: stdout.trim(), stderr: stderr.trim() }),
    );
    child.stdin.end(statement);
  });
}
function success(result) {
  assert.equal(result.code, 0, result.stderr);
  return result.stdout;
}
let seeded = false;
try {
  assert.equal(success(await sql("select current_database();")), database);
  success(
    await sql(`begin;
    insert into auth.users(id,is_anonymous,raw_user_meta_data) values('${account}',false,'{}');
    insert into private.music_catalogue_sources(media_id,last_used_at) values('${source}',now());
    insert into public.media_preferences(user_id,source_type,media_id,preference_state,source_event_id,source_event_at)
      values('${account}','youtube','${source}','liked','${randomUUID()}',now());
    set local role service_role;
    select public.enter_recording_reference('${account}','${recording}','Synthetic concurrent performance','owner:concurrency-fixture');
    select public.revise_recording_link('${account}','${source}','${recording}',0,'${randomUUID()}','accepted','owner:concurrency-fixture');
    commit;`),
  );
  seeded = true;
  const attempts = await Promise.all([
    sql(`begin;set local role service_role;
      select public.revise_recording_link('${account}','${source}','${recording}',1,'${randomUUID()}','disputed','owner:concurrency-left');
      select pg_sleep(0.5);commit;`),
    sql(`begin;set local role service_role;
      select public.revise_recording_link('${account}','${source}',null,1,'${randomUUID()}','unresolved','owner:concurrency-right');
      commit;`),
  ]);
  assert.equal(
    attempts.filter((result) => result.code === 0).length,
    1,
    "exactly one same-revision mutation succeeds",
  );
  const rejected = attempts.find((result) => result.code !== 0);
  assert.match(
    rejected.stderr,
    /40001/,
    "loser is a revision conflict, not an unrelated failure",
  );
  assert.equal(
    success(
      await sql(`select revision||':'||(select count(*) from private.recording_link_revisions where account_id='${account}')
    from private.recording_source_links where account_id='${account}' and media_id='${source}';`),
    ),
    "2:2",
    "one head increment and one new audit revision survive",
  );
  console.log(
    "PASS: concurrent edits from revision 1 yield one winner, one 40001, head revision 2 and two audit entries.",
  );
} finally {
  if (seeded) {
    // Only random fixture IDs generated by this invocation are removed.
    success(
      await sql(`begin;delete from auth.users where id='${account}';
      delete from private.music_catalogue_sources where media_id='${source}';commit;`),
    );
    console.log("PASS: synthetic account/source fixtures removed.");
  }
}
